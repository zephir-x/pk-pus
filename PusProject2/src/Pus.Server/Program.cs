using System;
using System.Linq;
using System.Net;
using System.Net.Security;
using System.Net.Sockets;
using System.Security.Cryptography.X509Certificates;
using System.Text;

namespace Pus.Server
{
    /// <summary>
    /// The main server application demonstrating secure TLS communication.
    /// </summary>
    class Program
    {
        static void Main(string[] args)
        {
            bool isTls = args.Contains("--tls");
            int port = 8080;

            if (isTls)
            {
                RunTlsServer(port);
            }
            else
            {
                Console.WriteLine("Please specify a protocol flag (e.g., --tls)");
            }
        }

        /// <summary>
        /// Runs a TCP server that wraps the connection in an SslStream to provide TLS encryption.
        /// </summary>
        static void RunTlsServer(int port)
        {
            // 1. Load the server's certificate and private key generated by OpenSSL
            // .NET 8 natively supports loading PEM files on Linux without converting to PFX
            string certPath = "scripts/certs/server.crt";
            string keyPath = "scripts/certs/server.key";
            
            using X509Certificate2 serverCertificate = X509Certificate2.CreateFromPemFile(certPath, keyPath);
            Console.WriteLine($"[TLS] Loaded Server Certificate: {serverCertificate.Subject}");

            // 2. Create standard IPv4 TCP socket (Layer 4)
            Socket serverSocket = new Socket(AddressFamily.InterNetwork, SocketType.Stream, ProtocolType.Tcp);
            serverSocket.Bind(new IPEndPoint(IPAddress.Any, port));
            serverSocket.Listen(10);
            
            Console.WriteLine($"[TLS] Server is listening on port {port}...");

            while (true)
            {
                // 3. Accept incoming raw TCP connection
                Socket clientSocket = serverSocket.Accept();
                Console.WriteLine($"[TLS] TCP connection accepted from: {clientSocket.RemoteEndPoint}");

                try
                {
                    // 4. Wrap the raw Socket in a NetworkStream, then in an SslStream (Layer 7 / TLS)
                    using NetworkStream networkStream = new NetworkStream(clientSocket);
                    using SslStream sslStream = new SslStream(networkStream, false);

                    // 5. Perform the TLS Handshake (Server Hello, Certificate Exchange, Key Negotiation)
                    // clientCertificateRequired is false for Grade 3.0 (no mTLS yet)
                    sslStream.AuthenticateAsServer(serverCertificate, clientCertificateRequired: false, checkCertificateRevocation: false);
                    Console.WriteLine("[TLS] Handshake successful! Connection is now encrypted.");
                    Console.WriteLine($"[TLS] Cipher Algorithm: {sslStream.CipherAlgorithm}, Protocol: {sslStream.SslProtocol}");

                    // 6. Securely read data from the client
                    byte[] buffer = new byte[2048];
                    int receivedBytes = sslStream.Read(buffer, 0, buffer.Length);
                    string message = Encoding.UTF8.GetString(buffer, 0, receivedBytes);
                    Console.WriteLine($"[TLS] Decrypted message received: {message}");

                    // 7. Securely send a response back
                    string response = $"TLS Server securely acknowledges receipt of: {message}";
                    byte[] responseData = Encoding.UTF8.GetBytes(response);
                    sslStream.Write(responseData, 0, responseData.Length);
                    
                    Console.WriteLine("[TLS] Encrypted response sent to client.\n");
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"[TLS Error]: {ex.Message}\n");
                }
                finally
                {
                    // Always close the underlying socket when done
                    clientSocket.Close();
                }
            }
        }
    }
}